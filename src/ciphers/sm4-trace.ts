// Spec-accurate SM4 round tracer (GB/T 32907-2016).
//
// The production SM4 encrypt/decrypt path in this demo comes from the `gm-crypto`
// library and is checked byte-for-byte against the official KAT vector. This module
// exists ONLY to expose the genuine per-round intermediate state so the round
// animation shows real data, not a decorative tally. Its final output is asserted
// against gm-crypto / the KAT in the unit tests, so it cannot silently drift into a
// fake: if the trace stops matching the standard, the test fails.
//
// SM4 keeps the 128-bit block as four 32-bit big-endian words X0 X1 X2 X3. Each of
// the 32 rounds computes:
//   Xi+4 = Xi XOR T( Xi+1 XOR Xi+2 XOR Xi+3 XOR rk[i] )
// where T = L(tau(.)): tau applies the S-box to each byte, L is the linear diffusion
//   L(B) = B ^ rotl(B,2) ^ rotl(B,10) ^ rotl(B,18) ^ rotl(B,24).
// The ciphertext is the reverse of the last four words (R transform).

